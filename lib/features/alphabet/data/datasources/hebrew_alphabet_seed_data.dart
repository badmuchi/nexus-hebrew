  /// Calculates the numerical Gematria value of any Hebrew text.
  static int calculateGematria(String text) {
    var sum = 0;
    for (final rune in text.runes) {
      final char = String.fromCharCode(rune);
      sum += _gematriaMap[char] ?? 0;
    }
    return sum;
  }

  /// Breakdown of each Hebrew character's value for a given word.
  static List<MapEntry<String, int>> getGematriaBreakdown(String text) {
    final list = <MapEntry<String, int>>[];
    for (final rune in text.runes) {
      final char = String.fromCharCode(rune);
      final val = _gematriaMap[char];
      if (val != null) {
        list.add(MapEntry(char, val));
      }
    }
    return list;
  }

