  final String nameRussian;
  final String visualMnemonicRu;
  final String strokeGuideRu;
  final bool isSofit;
  final String sampleWordHebrew;
  final String sampleWordTranslationRu;

  const CursiveLetterEntry({
    required this.printed,
    required this.nameHebrew,
    required this.nameRussian,
    required this.visualMnemonicRu,
    required this.strokeGuideRu,
    this.isSofit = false,
    required this.sampleWordHebrew,
    required this.sampleWordTranslationRu,
  });

  @override
  List<Object?> get props => [
        printed,
        nameHebrew,
        nameRussian,
        visualMnemonicRu,
        strokeGuideRu,
        isSofit,
        sampleWordHebrew,
        sampleWordTranslationRu,
      ];
}

