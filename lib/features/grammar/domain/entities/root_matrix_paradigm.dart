/// Single verb form within a root transformation paradigm.
class RootBinyanForm {
  final Binyan binyan;
  final String vocalized;
  final String normalized;
  final String transliteration;
  final String translationRu;
  final String nuanceRu;
  final String exampleHebrew;
  final String exampleRu;

  const RootBinyanForm({
    required this.binyan,
    required this.vocalized,
    required this.normalized,
    required this.transliteration,
    required this.translationRu,
    required this.nuanceRu,
    required this.exampleHebrew,
    required this.exampleRu,
  });
}

